def sur(vat, city=0.07, half=True):
    from decimal import Decimal as D, ROUND_HALF_UP as H
    q = lambda x: D(x).quantize(D("0.01"), rounding=H)
    v = D(str(vat)); f = D("0.5") if half else D(1)
    return str(sum(q(v * D(str(r)) * f) for r in (city, 0.03, 0.02)))

